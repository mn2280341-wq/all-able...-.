    /**
     * تفعيل قارئ الشاشة
     */
    enableScreenReader() {
        this.screenReader = {
            enabled: true,
            readElement: (element) => {
                const text = element.textContent || element.getAttribute('aria-label');
                if (text) {
                    speak(text, {
                        rate: this.preferences.voiceSpeed,
                        pitch: this.preferences.voicePitch
                    });
                }
            }
        };

        // إضافة مستمع للنقر على العناصر
        document.addEventListener('click', (e) => {
            if (this.screenReader.enabled) {
                this.screenReader.readElement(e.target);
            }
        });

        console.log('✅ تم تفعيل قارئ الشاشة');
    }

    /**
     * تفعيل التحكم الصوتي
     */
    enableVoiceControl() {
        if (!this.isVoiceControlActive) {
            this.startVoiceControl();
        }
    }

    /**
     * بدء التحكم الصوتي
     */
    startVoiceControl() {
        this.voiceRecognition = startVoiceRecognition(
            (transcript) => {
                this.handleVoiceCommand(transcript);
            },
            { continuous: true, interimResults: false }
        );

        this.isVoiceControlActive = true;
        console.log('🎤 تم تفعيل التحكم الصوتي');
    }

    /**
     * إيقاف التحكم الصوتي
     */
    stopVoiceControl() {
        if (this.voiceRecognition) {
            this.voiceRecognition.stop();
            this.voiceRecognition = null;
        }
        this.isVoiceControlActive = false;
        console.log('🎤 تم إيقاف التحكم الصوتي');
    }

    /**
     * معالجة الأوامر الصوتية
     */
    async handleVoiceCommand(command) {
        console.log('🎤 أمر صوتي:', command);
        showNotification(`جاري التحليل: ${command}`, 'info');

        try {
            // إرسال الأمر للذكاء الاصطناعي
            const result = await callBackend('/api/voice-command', 'POST', { command });

            if (result && result.status === 'success') {
                const { action, parameter, reply } = result;

                // الرد الصوتي
                speak(reply, {
                    onend: () => {
                        this.executeAction(action, parameter);
                    }
                });
            } else {
                speak('عفواً، لم أستطع فهم الأمر.');
            }
        } catch (e) {
            console.error(e);
            speak('حدث خطأ في الاتصال.');
        }
    }

    /**
     * تنفيذ الإجراء المطلوب من الذكاء الاصطناعي
     */
    executeAction(action, parameter) {
        console.log(`🤖 وتنفيذ AI Action: ${action} -> ${parameter}`);

        switch (action) {
            case 'navigate':
                if (parameter) window.location.href = parameter;
                break;

            case 'set_theme':
                if (parameter && ['hearing', 'visual', 'motor', 'cognitive'].includes(parameter)) {
                    this.setDisabilityType(parameter);
                }
                break;

            case 'trigger_emergency':
                document.getElementById('emergency-btn')?.click();
                if (window.location.pathname.indexOf('emergency.html') === -1) {
                    window.location.href = 'emergency.html';
                }
                break;

            case 'read_screen':
                const content = document.body.innerText;
                speak(content);
                break;

            default:
                console.log('إجراء غير مبرمج:', action);
        }
    }


